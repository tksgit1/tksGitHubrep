a = 13
b = 33

print('a = 13, b = 33')

#Greater than(>)
#Returns True if the left operand is greater than the right.
print('Returns True if the left operand is greater than the right -------------a > b-', a > b)

#Less than(<)
#Returns True if the left operand is less than the right.
print('Returns True if the left operand is less than the right ----------------a < b', a < b)

#Equal to(==)
#Returns True if both operands are equal
print('Returns True if both operands are equal --------------------------------a == b', a == b)

#Not equal to(!=)
#Returns True if operands are not equal.
print('Returns True if operands are not equal ---------------------------------a != b', a != b)

#Greater than or equal to(>=)
#Returns True if the left operand is greater than or equal to the right.
print('Returns True if the left operand is greater than or equal to the right -a >= b', a >= b)

#Less than or equal to(<=)
#Returns True if the left operand is less than or equal to the right.
print('Returns True if the left operand is less than or equal to the right ----a <= b', a <= b)



