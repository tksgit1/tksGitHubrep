for i in range(10):
    print("i =", i)

    # Using pass
    if i == 1:

        print('if i == 1:\n'
        '---> pass\n')
        pass


    # Using continue
    if i == 2:
        print('if i == 2:\n'
              '---> continue\n')
        continue

    # Using break
    if i == 5:
        print('if i == 5:\n'
              '---> break\n')
        break


