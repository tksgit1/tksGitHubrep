# Casting variables

#int()
#Converts values to an integer
s = "10"  # Initially a string
n = int(s)  # Cast string to integer
print('s = "10"  # Initially a string')
print('n = int(s)  # Cast string to integer--', n)

#float()
#Converts values to a floating-point number.
cnt = 5
f = float(cnt)  # Cast integer to float
print('cnt = 5')
print('f = float(cnt)  # Cast integer to float--', f )

#str()
#Converts values to a string.
age = 25
s2 = str(age)  # Cast integer to string
print('age = 25')
print('s2 = str(age)  # Cast integer to string--', s2)




