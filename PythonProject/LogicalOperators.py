a = True
b = False

print('a = True, b = False')

#Logical AND (and)
#Returns True if both conditions are True.
print('Returns True if both conditions are True --a and b--', a and b)

#Logical OR (or)
#Returns True if at least one condition is True.
print('Returns True if at least one condition is True --a or b--', a or b)


#Logical NOT (not)
#Reverses the boolean value.
print('Reverses the boolean value --not a--', not a)
