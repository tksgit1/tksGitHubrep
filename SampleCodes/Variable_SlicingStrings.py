b = "Hello, World!"
print(b[2:5])

print("\n#Slice From the Start")
b = "Hello, World!"
print(b[:5])

print("\n#Slice To the End")
b = "Hello, World!"
print(b[2:])

print("\n#Negative Indexing")
b = "Hello, World!"
print(b[-5:-2])

print("\n#Negative Indexing--Reverse character")
b = "Hello, World!"
print(b[::-1])
